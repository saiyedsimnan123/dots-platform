  // --- Markdown Formatting ---

  private formatMarkdownReport(report: ResearchReport): string {
    const lines: string[] = [];

    lines.push(`# Research Report: ${report.researchQuestion}`);
    lines.push('');
    lines.push(`**Status**: \`${report.completionStatus}\` | **Sources Evaluated**: ${report.evidenceAndSources.length}`);
    lines.push('');
    lines.push('---');
    lines.push('');
    lines.push('## Executive Summary');
    lines.push(report.executiveSummary);
    lines.push('');

    if (report.keyFindings.length > 0) {
      lines.push('## Key Findings');
      for (const f of report.keyFindings) {
        lines.push(`- ${f}`);
      }
      lines.push('');
    }

    if (report.evidenceAndSources.length > 0) {
      lines.push('## Evidence & Sources Catalog');
      for (const src of report.evidenceAndSources) {
        lines.push(`### [${src.title}](${src.url})`);
        lines.push(`- **Domain**: \`${src.domain}\` | **Retrieved**: ${src.retrievedAt}`);
        lines.push(`- **Summary**: ${src.summary}`);
        if (src.relevantEvidence.length > 0) {
          lines.push('- **Extracted Evidence**:');
          for (const ev of src.relevantEvidence) {
            lines.push(`  > "${ev}"`);
          }
        }
        lines.push('');
      }
    }

    if (report.agreements.length > 0) {
      lines.push('## Cross-Source Agreements');
      for (const a of report.agreements) {
        lines.push(`- ${a}`);
      }
      lines.push('');
    }

    if (report.conflictingEvidence.length > 0) {
      lines.push('## Conflicting Evidence & Contradictions');
      for (const c of report.conflictingEvidence) {
        lines.push(`- ${c}`);
      }
      lines.push('');
    }

    if (report.inferences.length > 0) {
      lines.push('## Inferences');
      for (const inf of report.inferences) {
        lines.push(`- ${inf}`);
      }
      lines.push('');
    }

    if (report.unverifiedClaims.length > 0) {
      lines.push('## Unverified Single-Source Claims');
      for (const u of report.unverifiedClaims) {
        lines.push(`- ${u}`);
      }
      lines.push('');
    }

    if (report.unestablishedInformation.length > 0) {
      lines.push('## Unestablished Information & Gaps');
      for (const g of report.unestablishedInformation) {
        lines.push(`- ${g}`);
      }
      lines.push('');
    }

    if (report.limitationsAndUncertainty.length > 0) {
      lines.push('## Limitations & Uncertainty');
      for (const l of report.limitationsAndUncertainty) {
        lines.push(`- ${l}`);
      }
      lines.push('');
    }

    if (report.openQuestions.length > 0 || report.suggestedNextSteps.length > 0) {
      lines.push('## Open Questions & Next Steps');
      if (report.openQuestions.length > 0) {
        lines.push('### Open Questions');
        for (const q of report.openQuestions) {
          lines.push(`1. ${q}`);
        }
        lines.push('');
      }
      if (report.suggestedNextSteps.length > 0) {
        lines.push('### Suggested Next Steps');
        for (const s of report.suggestedNextSteps) {
          lines.push(`1. ${s}`);
        }
        lines.push('');
      }
    }

    return lines.join('\n');
  }

  // --- Output Helper ---

  private formatAgentOutput(
    input: AgentInput,
    context: AgentExecutionContext,
    report: ResearchReport,
    stepsExecuted: number,
    startMs: number
  ): AgentOutput {
    const reportMarkdown = this.formatMarkdownReport(report);

    // If the research stage failed completely, map output status to FAILED
    const agentStatus: AgentExecutionStatus =
      report.completionStatus === 'FAILED' ? 'FAILED' : 'COMPLETED';

    return {
      agentId: this.id,
      taskId: input.taskId ?? context.taskId,
      status: agentStatus,
      result: {
        report,
        reportMarkdown,
        response: reportMarkdown,
        summary: report.executiveSummary,
        completionStatus: report.completionStatus,
        sourcesCount: report.evidenceAndSources.length,
        findingsCount: report.keyFindings.length
      },
      summary: report.executiveSummary,
      error: report.completionStatus === 'FAILED' ? report.executiveSummary : undefined,
      stepsExecuted,
      durationMs: Math.max(0, Date.now() - startMs)
    };
  }

  // --- URL Helpers ---

  private normalizeUrl(rawUrl: string): string | null {
    try {
      const u = new URL(rawUrl);
      if (u.protocol !== 'http:' && u.protocol !== 'https:') {
        return null;
      }
      // Strip userinfo, hash, and trailing slash
      u.username = '';
      u.password = '';
      u.hash = '';
      return u.toString();
    } catch {
      return null;
    }
  }

  private extractDomain(urlStr: string): string {
    try {
      const u = new URL(urlStr);
      return u.hostname;
    } catch {
      return 'unknown';
    }
  }
