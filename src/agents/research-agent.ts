/**
 * Next-Generation Dots AI Platform - Research Agent (Phase 3A)
 *
 * Architectural Mandate:
 * Specialized, evidence-based autonomous research agent implementing the shared IAgent contract.
 *
 * Guarantees:
 * 1. Strict evidence grounding: Zero fabricated sources, quotations, URLs, or findings.
 * 2. Unambiguous distinction between supported findings, conflicting evidence, inferences,
 *    unverified claims, and unestablished information.
 * 3. Robust query decomposition and source deduplication.
 * 4. Honest completion status reporting (COMPLETED, PARTIAL, INSUFFICIENT_EVIDENCE, FAILED).
 * 5. Full compliance with PolicyEngine, ApprovalBroker, cancellation signals, and secret scrubbing.
 * 6. Untrusted web content isolation preventing prompt-injection overrides.
 */

